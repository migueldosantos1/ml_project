print(digits.DESCR)

print(digits.data)

print(digits.data.shape)

print(digits.feature_names)

print(digits.target)

print(digits.target_names)

import matplotlib.pyplot as plt

example = digits.data[100,:]
example = np.reshape(example, (8,8))

